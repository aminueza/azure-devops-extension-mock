import { GraphRestClient, GraphTraversalDirection } from "azure-devops-extension-api/Graph";
import { GroupScopeType } from "azure-devops-extension-api/Identities";
import { AvatarSize } from "azure-devops-extension-api/Profile";
import { getClient, getRegisteredMockClient, MockGraphRestClient } from "../azure-devops-extension-api";
import { RestClientBase } from "../azure-devops-extension-api/common/RestClientBase";
import {
    avatars,
    cachePolicies,
    groups,
    identityTranslations,
    members,
    memberships,
    providerInfos,
    scopes,
    servicePrincipals,
    storageKeys,
    subjects,
    users
} from "../azure-devops-extension-api/graph/Data";

const UNKNOWN = "aad.unknown-descriptor";

describe("GraphRestClient mock", () => {
    beforeAll(() => {
        jest.spyOn(console, "log").mockImplementation(() => undefined);
    });
    afterAll(() => {
        jest.restoreAllMocks();
    });

    const client = getClient(GraphRestClient);

    it("is registered for the real client and exported", () => {
        expect(getRegisteredMockClient(GraphRestClient)).toBe(MockGraphRestClient);
        const direct = new MockGraphRestClient({});
        expect(direct).toBeInstanceOf(RestClientBase);
        expect(direct.TYPE).toBe(GraphRestClient);
    });

    it("seeds consistent fixtures", () => {
        expect(users.length).toBe(5);
        expect(groups.map(g => g.displayName)).toEqual(["Project Administrators", "Contributors", "Readers"]);
        expect(servicePrincipals.length).toBe(2);
        expect(scopes.length).toBe(2);
        expect(members.length).toBe(10);
        expect(subjects.length).toBe(12);
        expect(memberships.length).toBe(8);
        expect(new Set(subjects.map(s => s.descriptor)).size).toBe(subjects.length);
        expect(storageKeys.map(k => k.descriptor)).toEqual(subjects.map(s => s.descriptor));
        expect(new Set(storageKeys.map(k => k.storageKey)).size).toBe(storageKeys.length);
        expect(providerInfos.map(p => p.descriptor)).toEqual(users.map(u => u.descriptor));
        expect(identityTranslations.length).toBe(users.length);
        expect(avatars.map(a => a.size)).toEqual([AvatarSize.Small, AvatarSize.Medium, AvatarSize.Large]);
        for (const user of users) {
            expect(user.descriptor.startsWith("aad.")).toBe(true);
            expect(user.subjectKind).toBe("user");
            expect(user.principalName).toBe(user.mailAddress);
            expect(user.metadataUpdateDate).toBeInstanceOf(Date);
        }
        for (const group of groups) {
            expect(group.descriptor.startsWith("vssgp.")).toBe(true);
            expect(group.subjectKind).toBe("group");
            expect(group.principalName).toContain(group.scopeName);
        }
        for (const servicePrincipal of servicePrincipals) {
            expect(servicePrincipal.descriptor.startsWith("aadsp.")).toBe(true);
            expect(servicePrincipal.principalName).toBe(servicePrincipal.applicationId);
        }
        expect(scopes[0].scopeType).toBe(GroupScopeType.ServiceHost);
        expect(scopes[1].scopeType).toBe(GroupScopeType.TeamProject);
    });

    it("deletes an avatar", async () => {
        await expect(client.deleteAvatar(users[0].descriptor)).resolves.toBeUndefined();
    });

    it("gets the medium avatar by default", async () => {
        const avatar = await client.getAvatar(users[0].descriptor);
        expect(avatar).toBe(avatars[1]);
        expect(avatar.size).toBe(AvatarSize.Medium);
        expect(avatar.timeStamp).toBeInstanceOf(Date);
        expect(avatar.value.length).toBe(16);
    });

    it("gets the avatar of the requested size", async () => {
        const avatar = await client.getAvatar(users[0].descriptor, AvatarSize.Large, "png");
        expect(avatar).toBe(avatars[2]);
    });

    it("fabricates an avatar for a size that is not seeded", async () => {
        const avatar = await client.getAvatar(users[0].descriptor, 9 as AvatarSize);
        expect(avatar.size).toBe(9);
        expect(avatar.isAutoGenerated).toBe(true);
    });

    it("sets an avatar", async () => {
        await expect(client.setAvatar(avatars[0], users[0].descriptor)).resolves.toBeUndefined();
    });

    it("gets the cache policies", async () => {
        const policies = await client.getCachePolicies();
        expect(policies).toBe(cachePolicies);
        expect(policies.cacheSize).toBeGreaterThan(0);
    });

    it("gets the descriptor of a known storage key", async () => {
        const result = await client.getDescriptor(storageKeys[0].storageKey);
        expect(result.value).toBe(storageKeys[0].descriptor);
        expect(result._links).toEqual({});
    });

    it("fabricates a descriptor for an unknown storage key", async () => {
        const result = await client.getDescriptor("no-such-key");
        expect(result.value.startsWith("aad.")).toBe(true);
        expect(subjects.map(s => s.descriptor)).not.toContain(result.value);
    });

    it("gets federated provider data with the default version", async () => {
        const data = await client.getFederatedProviderData(users[0].descriptor, "github.com");
        expect(data.subjectDescriptor).toBe(users[0].descriptor);
        expect(data.providerName).toBe("github.com");
        expect(data.version).toBe(1);
        expect(data.accessToken.length).toBe(40);
    });

    it("gets federated provider data with a version hint", async () => {
        const data = await client.getFederatedProviderData(users[0].descriptor, "github.com", 4);
        expect(data.version).toBe(4);
    });

    it("creates a group echoing the creation context", async () => {
        const context = {
            storageKey: "",
            displayName: "Release Managers",
            description: "People who ship",
            crossProject: false,
            descriptor: "",
            restrictedVisibility: false,
            specialGroupType: "Generic"
        };
        const group = await client.createGroup(context, scopes[0].descriptor, [groups[0].descriptor]);
        expect(group.displayName).toBe("Release Managers");
        expect(group.description).toBe("People who ship");
        expect(group.subjectKind).toBe("group");
        expect(group.origin).toBe("vsts");
    });

    it("deletes a group", async () => {
        await expect(client.deleteGroup(groups[0].descriptor)).resolves.toBeUndefined();
    });

    it("gets a known group", async () => {
        await expect(client.getGroup(groups[1].descriptor)).resolves.toBe(groups[1]);
    });

    it("fabricates an unknown group", async () => {
        const group = await client.getGroup("vssgp.unknown");
        expect(group.descriptor).toBe("vssgp.unknown");
        expect(group.subjectKind).toBe("group");
    });

    it("updates a group from a patch document", async () => {
        const updated = await client.updateGroup(groups[2].descriptor, [
            { op: "replace", path: "/displayName", value: "Viewers" },
            { op: "replace", path: "/description", value: "Read only" },
            { op: "replace", path: "/descriptor", value: "vssgp.other" }
        ]);
        expect(updated.descriptor).toBe(groups[2].descriptor);
        expect(updated.displayName).toBe("Viewers");
        expect(updated.description).toBe("Read only");
        expect(updated.originId).toBe(groups[2].originId);
        expect(groups[2].displayName).toBe("Readers");
    });

    it("leaves a group unchanged when the patch document is not a list", async () => {
        const updated = await client.updateGroup(groups[0].descriptor, {});
        expect(updated).toEqual(groups[0]);
    });

    it("translates a master id to its local id", async () => {
        const { masterId, localId } = identityTranslations[0];
        await expect(client.translate(masterId)).resolves.toBe(localId);
    });

    it("translates a local id to its master id", async () => {
        const { masterId, localId } = identityTranslations[1];
        await expect(client.translate(undefined, localId)).resolves.toBe(masterId);
    });

    it("fabricates a translation for an unknown id and for no id", async () => {
        const known = identityTranslations.flatMap(t => [t.masterId, t.localId]);
        const unknown = await client.translate("no-such-master");
        const none = await client.translate();
        expect(typeof unknown).toBe("string");
        expect(known).not.toContain(unknown);
        expect(known).not.toContain(none);
    });

    it("looks up members by descriptor", async () => {
        const found = await client.lookupMembers({
            lookupKeys: [
                { descriptor: users[0].descriptor },
                { descriptor: groups[0].descriptor },
                { descriptor: servicePrincipals[0].descriptor },
                { descriptor: UNKNOWN }
            ]
        });
        expect(Object.keys(found).length).toBe(4);
        expect(found[users[0].descriptor]).toBe(users[0]);
        expect(found[groups[0].descriptor]).toBe(groups[0]);
        expect(found[servicePrincipals[0].descriptor]).toBe(servicePrincipals[0]);
        expect(found[UNKNOWN].descriptor).toBe(UNKNOWN);
    });

    it("looks up no members for an empty lookup", async () => {
        await expect(client.lookupMembers({ lookupKeys: [] })).resolves.toEqual({});
    });

    it("gets a known member by descriptor", async () => {
        await expect(client.getMemberByDescriptor(groups[1].descriptor)).resolves.toBe(groups[1]);
    });

    it("fabricates an unknown member", async () => {
        const member = await client.getMemberByDescriptor(UNKNOWN);
        expect(member.descriptor).toBe(UNKNOWN);
        expect(typeof member.principalName).toBe("string");
    });

    it("adds a membership", async () => {
        const membership = await client.addMembership(users[0].descriptor, groups[2].descriptor);
        expect(membership).toEqual({
            memberDescriptor: users[0].descriptor,
            containerDescriptor: groups[2].descriptor,
            _links: {}
        });
    });

    it("checks membership existence", async () => {
        await expect(client.checkMembershipExistence(users[0].descriptor, groups[0].descriptor)).resolves.toBe(true);
        await expect(client.checkMembershipExistence(users[0].descriptor, groups[1].descriptor)).resolves.toBe(false);
        await expect(client.checkMembershipExistence(UNKNOWN, groups[0].descriptor)).resolves.toBe(false);
    });

    it("gets a known membership", async () => {
        const membership = await client.getMembership(users[1].descriptor, groups[1].descriptor);
        expect(membership).toBe(memberships[1]);
    });

    it("fabricates an unknown membership", async () => {
        const membership = await client.getMembership(users[1].descriptor, groups[0].descriptor);
        expect(memberships).not.toContain(membership);
        expect(membership.memberDescriptor).toBe(users[1].descriptor);
        expect(membership.containerDescriptor).toBe(groups[0].descriptor);
    });

    it("removes a membership", async () => {
        await expect(client.removeMembership(users[0].descriptor, groups[0].descriptor)).resolves.toBeUndefined();
    });

    it("lists the containers of a subject by default and upwards", async () => {
        const byDefault = await client.listMemberships(users[0].descriptor);
        const up = await client.listMemberships(users[0].descriptor, GraphTraversalDirection.Up, 1);
        expect(byDefault.map(m => m.containerDescriptor)).toEqual([groups[0].descriptor]);
        expect(up).toEqual(byDefault);
    });

    it("lists the members of a container downwards", async () => {
        const down = await client.listMemberships(groups[1].descriptor, GraphTraversalDirection.Down);
        expect(down.map(m => m.memberDescriptor)).toEqual([
            users[1].descriptor,
            users[4].descriptor,
            servicePrincipals[0].descriptor,
            servicePrincipals[1].descriptor,
            groups[0].descriptor
        ]);
    });

    it("lists no memberships for an unknown subject", async () => {
        await expect(client.listMemberships(UNKNOWN)).resolves.toEqual([]);
    });

    it("gets the membership state", async () => {
        const state = await client.getMembershipState(users[0].descriptor);
        expect(state).toEqual({ active: true, _links: {} });
    });

    it("traverses memberships upwards by default", async () => {
        const traversal = await client.traverseMemberships(groups[0].descriptor);
        expect(traversal.subjectDescriptor).toBe(groups[0].descriptor);
        expect(traversal.traversedSubjects).toEqual([groups[1].descriptor]);
        expect(traversal.traversedSubjectIds).toEqual([
            storageKeys.find(k => k.descriptor === groups[1].descriptor)!.storageKey
        ]);
        expect(traversal.isComplete).toBe(true);
        expect(traversal.incompletenessReason).toBe("");
    });

    it("traverses memberships downwards", async () => {
        const traversal = await client.traverseMemberships(groups[0].descriptor, GraphTraversalDirection.Down, 2);
        expect(traversal.traversedSubjects).toEqual([users[0].descriptor, users[3].descriptor]);
        expect(traversal.traversedSubjectIds.length).toBe(2);
    });

    it("looks up membership traversals", async () => {
        const up = await client.lookupMembershipTraversals({
            lookupKeys: [{ descriptor: users[2].descriptor }, { descriptor: UNKNOWN }]
        });
        expect(up[users[2].descriptor].traversedSubjects).toEqual([groups[2].descriptor]);
        expect(up[UNKNOWN].subjectDescriptor).toBe(UNKNOWN);
        expect(up[UNKNOWN].traversedSubjects).toEqual([]);
        const down = await client.lookupMembershipTraversals(
            { lookupKeys: [{ descriptor: groups[2].descriptor }] },
            GraphTraversalDirection.Down,
            1
        );
        expect(down[groups[2].descriptor].traversedSubjects).toEqual([users[2].descriptor]);
    });

    it("gets provider info for a known user", async () => {
        const info = await client.getProviderInfo(users[0].descriptor);
        expect(info).toBe(providerInfos[0]);
        expect(info.originId).toBe(users[0].originId);
        expect(info.domain).toBe(users[0].domain);
    });

    it("fabricates provider info for an unknown user", async () => {
        const info = await client.getProviderInfo(UNKNOWN);
        expect(info.descriptor).toBe(UNKNOWN);
        expect(info.origin).toBe("aad");
        expect(typeof info.originId).toBe("string");
    });

    it("requests access", async () => {
        const payload = { message: "please", projectUri: "vstfs:///p", urlRequested: "https://example.com" };
        await expect(client.requestAccess(payload)).resolves.toBeUndefined();
    });

    it("resolves one mapping result per identity mapping", async () => {
        const response = await client.resolve({
            mappings: [
                { source: { principalName: "a@example.com" }, target: { principalName: "b@example.com" } },
                { source: { principalName: "c@example.com" }, target: { principalName: "d@example.com" } }
            ]
        });
        expect(response.code).toBe("Success");
        expect(response.errorMessage).toBe("");
        expect(response.mappingResults).toEqual([
            { code: "Success", errorMessage: "" },
            { code: "Success", errorMessage: "" }
        ]);
    });

    it("creates a scope from the creation context", async () => {
        const scope = await client.createScope(
            {
                name: "New Project",
                scopeType: GroupScopeType.Generic,
                adminGroupName: "Admins",
                adminGroupDescription: "Scope admins",
                creatorId: "creator",
                storageKey: ""
            },
            scopes[0].descriptor
        );
        expect(scope.displayName).toBe("New Project");
        expect(scope.scopeType).toBe(GroupScopeType.Generic);
        expect(scope).toMatchObject({ adminGroupName: "Admins", creatorId: "creator" });
        expect(scope.subjectKind).toBe("scope");
        expect(scope.descriptor.startsWith("scp.")).toBe(true);
    });

    it("deletes a scope", async () => {
        await expect(client.deleteScope(scopes[0].descriptor)).resolves.toBeUndefined();
    });

    it("gets a known scope", async () => {
        const scope = await client.getScope(scopes[0].descriptor);
        expect(scope).toBe(scopes[0]);
        expect(scope.isGlobal).toBe(true);
    });

    it("fabricates an unknown scope", async () => {
        const scope = await client.getScope("scp.unknown");
        expect(scope.descriptor).toBe("scp.unknown");
        expect(scope.scopeType).toBe(GroupScopeType.TeamProject);
    });

    it("updates a scope", async () => {
        const patch = [{ op: "replace", path: "/name", value: "Renamed" }];
        await expect(client.updateScope(scopes[0].descriptor, patch)).resolves.toBeUndefined();
    });

    it("creates a service principal echoing the creation context", async () => {
        const context = { storageKey: "", originId: "origin-1" };
        const servicePrincipal = await client.createServicePrincipal(context, [groups[0].descriptor]);
        expect(servicePrincipal.originId).toBe("origin-1");
        expect(servicePrincipal.subjectKind).toBe("servicePrincipal");
        expect(servicePrincipal.metaType).toBe("application");
    });

    it("deletes a service principal", async () => {
        await expect(client.deleteServicePrincipal(servicePrincipals[0].descriptor)).resolves.toBeUndefined();
    });

    it("gets a known service principal", async () => {
        await expect(client.getServicePrincipal(servicePrincipals[1].descriptor)).resolves.toBe(servicePrincipals[1]);
    });

    it("fabricates an unknown service principal", async () => {
        const servicePrincipal = await client.getServicePrincipal("aadsp.unknown");
        expect(servicePrincipal.descriptor).toBe("aadsp.unknown");
        expect(typeof servicePrincipal.applicationId).toBe("string");
    });

    it("updates a service principal", async () => {
        const context = { storageKey: "", originId: "origin-2" };
        const updated = await client.updateServicePrincipal(context, servicePrincipals[0].descriptor);
        expect(updated.descriptor).toBe(servicePrincipals[0].descriptor);
        expect(updated.originId).toBe("origin-2");
        expect(updated.applicationId).toBe(servicePrincipals[0].applicationId);
    });

    it("round-trips a storage key and its descriptor", async () => {
        const key = await client.getStorageKey(groups[0].descriptor);
        expect(key._links).toEqual({});
        expect(key.value).toBe(storageKeys.find(k => k.descriptor === groups[0].descriptor)!.storageKey);
        const descriptor = await client.getDescriptor(key.value);
        expect(descriptor.value).toBe(groups[0].descriptor);
    });

    it("fabricates a storage key for an unknown descriptor", async () => {
        const key = await client.getStorageKey(UNKNOWN);
        expect(typeof key.value).toBe("string");
        expect(storageKeys.map(k => k.storageKey)).not.toContain(key.value);
    });

    it("looks up subjects by descriptor", async () => {
        const found = await client.lookupSubjects({
            lookupKeys: [
                { descriptor: scopes[1].descriptor },
                { descriptor: users[3].descriptor },
                { descriptor: UNKNOWN }
            ]
        });
        expect(found[scopes[1].descriptor]).toBe(scopes[1]);
        expect(found[users[3].descriptor]).toBe(users[3]);
        expect(found[UNKNOWN].descriptor).toBe(UNKNOWN);
    });

    it("queries subjects by kind", async () => {
        const found = await client.querySubjects({ query: "", scopeDescriptor: "", subjectKind: ["Group"] });
        expect(found).toEqual(groups);
        const mixed = await client.querySubjects({
            query: "",
            scopeDescriptor: "",
            subjectKind: ["User", "ServicePrincipal"]
        });
        expect(mixed).toEqual([...users, ...servicePrincipals]);
    });

    it("queries subjects by display name", async () => {
        const found = await client.querySubjects({ query: "CONTRIB", scopeDescriptor: "", subjectKind: ["Group"] });
        expect(found).toEqual([groups[1]]);
        const none = await client.querySubjects({ query: "contrib", scopeDescriptor: "", subjectKind: ["User"] });
        expect(none).toEqual([]);
    });

    it("queries every kind of subject when no kind is given", async () => {
        const all = await client.querySubjects({ query: "", scopeDescriptor: "", subjectKind: [] });
        expect(all).toEqual(subjects);
        const named = await client.querySubjects({ query: users[0].displayName, scopeDescriptor: "", subjectKind: [] });
        expect(named).toContain(users[0]);
    });

    it("gets a known subject", async () => {
        await expect(client.getSubject(scopes[0].descriptor)).resolves.toBe(scopes[0]);
    });

    it("fabricates an unknown subject", async () => {
        const subject = await client.getSubject(UNKNOWN);
        expect(subject.descriptor).toBe(UNKNOWN);
        expect(typeof subject.subjectKind).toBe("string");
    });

    it("creates a user echoing the creation context", async () => {
        const context = { storageKey: "", principalName: "new.user@example.com" };
        const user = await client.createUser(context, [groups[1].descriptor]);
        expect(user.principalName).toBe("new.user@example.com");
        expect(user.subjectKind).toBe("user");
        expect(user.descriptor.startsWith("aad.")).toBe(true);
    });

    it("deletes a user", async () => {
        await expect(client.deleteUser(users[0].descriptor)).resolves.toBeUndefined();
    });

    it("gets a known user", async () => {
        await expect(client.getUser(users[2].descriptor)).resolves.toBe(users[2]);
    });

    it("fabricates an unknown user", async () => {
        const user = await client.getUser(UNKNOWN);
        expect(user.descriptor).toBe(UNKNOWN);
        expect(typeof user.mailAddress).toBe("string");
    });

    it("updates a user", async () => {
        const context = { storageKey: "", originId: "origin-3" };
        const updated = await client.updateUser(context, users[4].descriptor);
        expect(updated.descriptor).toBe(users[4].descriptor);
        expect(updated.originId).toBe("origin-3");
        expect(updated.displayName).toBe(users[4].displayName);
    });
});
