import {
    AvatarSize,
    CreateProfileContext,
    ProfileRestClient,
    ProfileState
} from "azure-devops-extension-api/Profile";
import { getClient, getRegisteredMockClient, MockProfileRestClient } from "../azure-devops-extension-api";
import {
    CORE_CONTAINER,
    makeAttributeDescriptor,
    makeAttributesContainer,
    makeAvatar,
    makeCoreProfileAttribute,
    makeCreateProfileContext,
    makeProfile,
    makeProfileAttribute,
    profileAttributes,
    profiles
} from "../azure-devops-extension-api/profile/Data";

describe("ProfileRestClient mock", () => {
    beforeAll(() => {
        jest.spyOn(console, "log").mockImplementation(() => undefined);
    });
    afterAll(() => {
        jest.restoreAllMocks();
    });

    const client = getClient(ProfileRestClient);

    it("is registered for the real client", () => {
        expect(getRegisteredMockClient(ProfileRestClient)).toBe(MockProfileRestClient);
    });

    it("deletes an attribute", async () => {
        await expect(client.deleteProfileAttribute("me", "Application;Theme")).resolves.toBeUndefined();
    });

    it("gets a known attribute", async () => {
        const attribute = await client.getProfileAttribute("me", "Application;Theme");
        expect(attribute).toBe(profileAttributes[0]);
        expect(attribute.value).toBe("dark");
    });

    it("fabricates an unknown attribute carrying the requested descriptor", async () => {
        const attribute = await client.getProfileAttribute("me", "Custom;Missing");
        expect(attribute.descriptor).toEqual({ containerName: "Custom", attributeName: "Missing" });
        expect(typeof attribute.value).toBe("string");
        expect(attribute.timeStamp).toBeInstanceOf(Date);
    });

    it("fabricates an attribute from a descriptor without a container separator", async () => {
        const attribute = await client.getProfileAttribute("me", "Standalone");
        expect(attribute.descriptor).toEqual({ containerName: "Standalone", attributeName: "Standalone" });
    });

    it("lists the attributes of a partition", async () => {
        const attributes = await client.getProfileAttributes("me", "Notifications");
        expect(attributes).toEqual([profileAttributes[2], profileAttributes[3]]);
    });

    it("lists nothing for an unknown partition", async () => {
        expect(await client.getProfileAttributes("me", "Missing", "2024-01-01", "1", true, "DisplayName")).toEqual([]);
    });

    it("sets an attribute", async () => {
        await expect(client.setProfileAttribute({ value: "light" }, "me", "Application;Theme")).resolves.toBeUndefined();
    });

    it("sets several attributes", async () => {
        await expect(
            client.setProfileAttributes({ count: 1, value: [profileAttributes[0]] }, "me")
        ).resolves.toBeUndefined();
    });

    it("gets a medium avatar by default", async () => {
        const avatar = await client.getAvatar("me");
        expect(avatar.size).toBe(AvatarSize.Medium);
        expect(avatar.isAutoGenerated).toBe(true);
        expect(avatar.value.length).toBe(16);
        expect(avatar.timeStamp).toBeInstanceOf(Date);
    });

    it.each([
        ["small", AvatarSize.Small],
        ["Medium", AvatarSize.Medium],
        ["LARGE", AvatarSize.Large],
        ["gigantic", AvatarSize.Medium]
    ])("gets an avatar of size %s", async (size, expected) => {
        expect((await client.getAvatar("me", size, "png")).size).toBe(expected);
    });

    it("previews an avatar", async () => {
        expect((await client.getAvatarPreview({}, "me")).size).toBe(AvatarSize.Medium);
        expect((await client.getAvatarPreview({}, "me", "large", "png", "Amanda")).size).toBe(AvatarSize.Large);
    });

    it("resets an avatar", async () => {
        await expect(client.resetAvatar("me")).resolves.toBeUndefined();
    });

    it("sets an avatar", async () => {
        await expect(client.setAvatar({}, "me")).resolves.toBeUndefined();
    });

    it("creates a profile from the posted context", async () => {
        const context: CreateProfileContext = {
            ...makeCreateProfileContext(),
            displayName: "Amanda Souza",
            emailAddress: "amanda@example.com",
            countryName: "Brazil",
            contactWithOffers: true,
            profileState: ProfileState.CustomReadOnly
        };
        const created = await client.createProfile(context, true);
        expect(created.profileState).toBe(ProfileState.CustomReadOnly);
        expect(created.coreAttributes.DisplayName.value).toBe("Amanda Souza");
        expect(created.coreAttributes.EmailAddress.value).toBe("amanda@example.com");
        expect(created.coreAttributes.CountryName.value).toBe("Brazil");
        expect(created.coreAttributes.ContactWithOffers.value).toBe(true);
        expect(typeof created.id).toBe("string");
        expect(created.applicationContainer.attributes).toEqual({});
    });

    it("gets the first profile for me", async () => {
        expect(await client.getProfile("me")).toBe(profiles[0]);
    });

    it("gets a known profile", async () => {
        expect(await client.getProfile(profiles[2].id, true, true, "Application", "DisplayName", false)).toBe(
            profiles[2]
        );
    });

    it("fabricates an unknown profile", async () => {
        const profile = await client.getProfile("missing-profile");
        expect(profile.id).toBe("missing-profile");
        expect(profile.profileState).toBe(ProfileState.Custom);
        expect(typeof profile.coreAttributes.DisplayName.value).toBe("string");
    });

    it("updates a profile", async () => {
        await expect(client.updateProfile(profiles[0], profiles[0].id)).resolves.toBeUndefined();
    });
});

describe("profile fixtures", () => {
    it("makes a descriptor from the given names or random ones", () => {
        expect(makeAttributeDescriptor("Box", "Key")).toEqual({ containerName: "Box", attributeName: "Key" });
        const random = makeAttributeDescriptor();
        expect(typeof random.containerName).toBe("string");
        expect(typeof random.attributeName).toBe("string");
    });

    it("makes an attribute for the given descriptor or a random one", () => {
        const descriptor = makeAttributeDescriptor("Box", "Key");
        expect(makeProfileAttribute(descriptor).descriptor).toBe(descriptor);
        expect(typeof makeProfileAttribute().descriptor.attributeName).toBe("string");
    });

    it("makes a core attribute in the core container", () => {
        const attribute = makeCoreProfileAttribute("DisplayName", "Amanda");
        expect(attribute.descriptor).toEqual({ containerName: CORE_CONTAINER, attributeName: "DisplayName" });
        expect(attribute.value).toBe("Amanda");
    });

    it("makes a container keyed by attribute name at the highest revision", () => {
        const first = { ...makeProfileAttribute(makeAttributeDescriptor("Box", "A")), revision: 3 };
        const second = { ...makeProfileAttribute(makeAttributeDescriptor("Box", "B")), revision: 7 };
        const container = makeAttributesContainer("Box", [first, second]);
        expect(container).toEqual({ containerName: "Box", revision: 7, attributes: { A: first, B: second } });
        expect(makeAttributesContainer("Empty")).toEqual({ containerName: "Empty", revision: 0, attributes: {} });
    });

    it("makes an avatar of the given size", () => {
        expect(makeAvatar(AvatarSize.Small).size).toBe(AvatarSize.Small);
        expect(makeAvatar().size).toBe(AvatarSize.Medium);
        for (const byte of makeAvatar().value) {
            expect(byte).toBeGreaterThanOrEqual(0);
            expect(byte).toBeLessThanOrEqual(255);
        }
    });

    it("makes a profile carrying its application attributes", () => {
        const attribute = makeProfileAttribute(makeAttributeDescriptor("Application", "Theme"));
        const profile = makeProfile(makeCreateProfileContext(), [attribute]);
        expect(profile.applicationContainer.attributes.Theme).toBe(attribute);
    });

    it("seeds profiles with unique ids and the application attributes on the first", () => {
        expect(new Set(profiles.map(p => p.id)).size).toBe(profiles.length);
        expect(Object.keys(profiles[0].applicationContainer.attributes)).toEqual(["Theme", "Locale"]);
        expect(profiles[2].profileState).toBe(ProfileState.ReadOnly);
    });

    it("seeds attributes with unique descriptors", () => {
        const keys = profileAttributes.map(a => `${a.descriptor.containerName};${a.descriptor.attributeName}`);
        expect(new Set(keys).size).toBe(keys.length);
    });
});
