import { fake } from "../common/fixtures";
import {
    AttributeDescriptor,
    AttributesContainer,
    Avatar,
    AvatarSize,
    CoreProfileAttribute,
    CreateProfileContext,
    Profile,
    ProfileAttribute,
    ProfileState
} from "azure-devops-extension-api/Profile";

export const CORE_CONTAINER = "Core";

export const makeAttributeDescriptor = (
    containerName: string = fake.lorem.word(),
    attributeName: string = fake.lorem.slug(2)
): AttributeDescriptor => ({ containerName, attributeName });

export const makeProfileAttribute = (
    descriptor: AttributeDescriptor = makeAttributeDescriptor()
): ProfileAttribute => ({
    descriptor,
    revision: fake.number.int({ min: 1, max: 20 }),
    timeStamp: fake.date.recent(),
    value: fake.lorem.words(2)
});

export const makeCoreProfileAttribute = (attributeName: string, value: any): CoreProfileAttribute => ({
    descriptor: makeAttributeDescriptor(CORE_CONTAINER, attributeName),
    revision: 1,
    timeStamp: fake.date.recent(),
    value
});

export const makeAttributesContainer = (
    containerName: string,
    members: ProfileAttribute[] = []
): AttributesContainer => ({
    containerName,
    revision: members.reduce((highest, attribute) => Math.max(highest, attribute.revision), 0),
    attributes: Object.fromEntries(members.map(attribute => [attribute.descriptor.attributeName, attribute]))
});

export const makeAvatar = (size: AvatarSize = AvatarSize.Medium): Avatar => ({
    isAutoGenerated: true,
    size,
    timeStamp: fake.date.recent(),
    value: Array.from({ length: 16 }, () => fake.number.int({ min: 0, max: 255 }))
});

export const makeCreateProfileContext = (): CreateProfileContext => ({
    ciData: {},
    contactWithOffers: false,
    countryName: fake.helpers.arrayElement(["Brazil", "Portugal", "Canada", "Germany"]),
    displayName: fake.person.fullName(),
    emailAddress: fake.internet.email(),
    hasAccount: true,
    language: "en-US",
    phoneNumber: `+1${fake.number.int({ min: 2_000_000_000, max: 9_999_999_999 })}`,
    profileState: ProfileState.Custom
});

export const makeProfile = (
    context: CreateProfileContext = makeCreateProfileContext(),
    applicationAttributes: ProfileAttribute[] = []
): Profile => ({
    id: fake.string.uuid(),
    profileState: context.profileState,
    revision: fake.number.int({ min: 1, max: 500 }),
    coreRevision: fake.number.int({ min: 1, max: 500 }),
    timeStamp: fake.date.recent(),
    coreAttributes: {
        DisplayName: makeCoreProfileAttribute("DisplayName", context.displayName),
        EmailAddress: makeCoreProfileAttribute("EmailAddress", context.emailAddress),
        CountryName: makeCoreProfileAttribute("CountryName", context.countryName),
        ContactWithOffers: makeCoreProfileAttribute("ContactWithOffers", context.contactWithOffers)
    },
    applicationContainer: makeAttributesContainer("Application", applicationAttributes)
});

export const profileAttributes: ProfileAttribute[] = [
    { ...makeProfileAttribute(makeAttributeDescriptor("Application", "Theme")), value: "dark" },
    { ...makeProfileAttribute(makeAttributeDescriptor("Application", "Locale")), value: "pt-BR" },
    { ...makeProfileAttribute(makeAttributeDescriptor("Notifications", "Digest")), value: "weekly" },
    { ...makeProfileAttribute(makeAttributeDescriptor("Notifications", "Mentions")), value: "enabled" }
];

export const profiles: Profile[] = [
    makeProfile(
        makeCreateProfileContext(),
        profileAttributes.filter(attribute => attribute.descriptor.containerName === "Application")
    ),
    makeProfile(),
    makeProfile({ ...makeCreateProfileContext(), profileState: ProfileState.ReadOnly })
];
